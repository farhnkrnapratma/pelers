pub fn token_name(kind: i32) -> &'static str {
    TOKEN_NAMES.get(kind as usize).copied().unwrap_or("INVALID")
}

pub fn keyword_kind(word: &str) -> Option<i32> {
    let kind = match word {
        "requirementdiagram" => T::Rd,
        "id" => T::Id,
        "text" => T::Text,
        "risk" => T::Risk,
        "verifymethod" => T::Verifymthd,
        "requirement" => T::Requirement,
        "functionalrequirement" => T::FunctionalRequirement,
        "interfacerequirement" => T::InterfaceRequirement,
        "performancerequirement" => T::PerformanceRequirement,
        "physicalrequirement" => T::PhysicalRequirement,
        "designconstraint" => T::DesignConstraint,
        "low" => T::LowRisk,
        "medium" => T::MedRisk,
        "high" => T::HighRisk,
        "analysis" => T::VerifyAnalysis,
        "demonstration" => T::VerifyDemonstration,
        "inspection" => T::VerifyInspection,
        "test" => T::VerifyTest,
        "element" => T::Element,
        "contains" => T::Contains,
        "copies" => T::Copies,
        "derives" => T::Derives,
        "satisfies" => T::Satisfies,
        "verifies" => T::Verifies,
        "refines" => T::Refines,
        "traces" => T::Traces,
        "type" => T::Type,
        "docref" => T::Docref,
        "style" => T::Style,
        "classdef" => T::Classdef,
        "class" => T::Class,
        _ => return None,
    };
    Some(kind as i32)
}
